// Number formatting — UZS with space-separated thousands
function fmtUZS(n) {
  return String(Math.round(n)).replace(/\B(?=(\d{3})+(?!\d))/g, " ");
}

// Phone mask: +998 (XX) XXX-XX-XX
function maskPhone(raw) {
  const digits = (raw || "").replace(/\D/g, "");
  // Strip leading 998 if present, also allow user typing without it
  let d = digits;
  if (d.startsWith("998")) d = d.slice(3);
  d = d.slice(0, 9);
  if (!d) return "";
  let out = "+998";
  if (d.length > 0) out += " (" + d.slice(0, 2);
  if (d.length >= 2) out += ")";
  if (d.length > 2) out += " " + d.slice(2, 5);
  if (d.length > 5) out += "-" + d.slice(5, 7);
  if (d.length > 7) out += "-" + d.slice(7, 9);
  return out;
}

function useT(locale) {
  const dict = I18N[locale] || I18N.uz;
  return React.useCallback((path) => {
    return path.split(".").reduce((o, k) => (o ? o[k] : undefined), dict);
  }, [locale]);
}

